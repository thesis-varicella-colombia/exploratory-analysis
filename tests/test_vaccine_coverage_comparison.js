"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const root = path.resolve(__dirname, "..");
const context = vm.createContext({Intl, document:{addEventListener(){}}});
vm.runInContext(fs.readFileSync(path.join(root,"docs/vaccine_coverage_comparison.js"),"utf8"),context);
const csv = fs.readFileSync(path.join(root,"docs/data_processed/cobertura_vacunacion/vaccine_coverage_comparison.csv"),"utf8");
const rows = context.parseVaccineComparisonCsv(csv);
assert.equal(rows.length,22440);
assert.equal(Math.min(...rows.map(row=>row.year)),2016);
assert.equal(Math.max(...rows.map(row=>row.year)),2025);
const first = context.vaccineComparisonState(rows,2016,"first_dose","reference");
assert.equal(first.byCode.size,1122);
const medellin=first.byCode.get("05001");
const [populationHeader,...populationLines]=fs.readFileSync(path.join(root,"data/population_vaccine_ages_municipal_2016_2025.csv"),"utf8").trim().split(/\r?\n/);
const populationFields=populationHeader.split(",");
const populations=populationLines.map(line=>Object.fromEntries(line.split(",").map((value,i)=>[populationFields[i],value])));
const medellin2016=populations.find(row=>row.codigo_municipio==="05001"&&row.ano_epidemiologico==="2016");
assert.equal(medellin.dose_source_year,2015);
assert.equal(medellin.reference_age_group,"age_1");
assert.equal(medellin.reference_population,Number(medellin2016.poblacion_1_anio));
assert.equal(medellin.administrative_coverage_pct,100.2);
assert.ok(Math.abs(medellin.reference_coverage_pct-100*13918/Number(medellin2016.poblacion_1_anio))<1e-8);
const medellin2020=populations.find(row=>row.codigo_municipio==="05001"&&row.ano_epidemiologico==="2020");
const age5=Number(medellin2020.poblacion_5_anios);
const booster2020=context.vaccineComparisonState(rows,2020,"booster","reference").byCode.get("05001");
assert.equal(booster2020.reference_age_group,"age_5");
assert.equal(booster2020.reference_population,age5);
assert.ok(Math.abs(booster2020.reference_coverage_pct-100*10439/age5)<1e-8);
assert.equal(first.field,"reference_coverage_pct");
assert.equal(context.vaccineComparisonState(rows,2025,"first_dose","administrative").field,"administrative_coverage_pct");
const booster2019=context.vaccineComparisonState(rows,2019,"booster","reference");
assert.ok([...booster2019.byCode.values()].every(row=>row.reference_coverage_pct===null));
assert.notEqual(context.vaccineComparisonColor(0),context.vaccineComparisonColor(null));
assert.notEqual(context.vaccineComparisonColor(50),context.vaccineComparisonColor(100));
assert.notEqual(context.vaccineComparisonColor(100),context.vaccineComparisonColor(150));
assert.equal(context.vaccineComparisonColor(200),context.vaccineComparisonColor(350));
assert.ok(rows.some(row=>row.reference_coverage_pct>200));
assert.throws(()=>context.parseVaccineComparisonCsv(csv+csv.split("\n")[1]+"\n"),/duplicada/);
console.log("Vaccination map: calendar, real-data formulas, missingness, measures and color scale OK");
const survivors=context.vaccineComparisonState(rows,2016,"first_dose","survivors");
assert.equal(survivors.field,"survivor_coverage_pct");
assert.equal(survivors.byCode.get("05001").survivor_population,28968);
assert.ok(Math.abs(survivors.byCode.get("05001").survivor_coverage_pct-100*13918/28968)<1e-8);
assert.ok(rows.filter(row=>row.dose==="booster").every(row=>row.survivor_coverage_pct===null && row.survivor_status==="not_applicable_to_booster"));
